import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { S3Client, DeleteObjectCommand, HeadObjectCommand } from "@aws-sdk/client-s3";
import { createAttemptResultStorage, attemptResultKey } from "../server/storage/attempt-results.mjs";

const env = process.env;
const required = ["R2_ACCOUNT_ID", "R2_ACCESS_KEY_ID", "R2_SECRET_ACCESS_KEY", "R2_BUCKET"];
if (required.some(name => !env[name]?.trim())) {
  console.error("R2_ENV_MISSING");
  process.exit(1);
}
const client = new S3Client({
  region: "auto",
  endpoint: `https://${env.R2_ACCOUNT_ID}.r2.cloudflarestorage.com`,
  forcePathStyle: true,
  maxAttempts: 3,
  requestChecksumCalculation: "WHEN_REQUIRED",
  credentials: { accessKeyId: env.R2_ACCESS_KEY_ID, secretAccessKey: env.R2_SECRET_ACCESS_KEY },
});
const storage = createAttemptResultStorage({ env, client });
const jobId = randomUUID();
const tokenA = randomUUID(), tokenB = randomUUID(), tokenC = randomUUID();
const keys = [attemptResultKey(jobId, tokenA), attemptResultKey(jobId, tokenB), attemptResultKey(jobId, tokenC)];
let passed = false;
let cleanupPassed = true;

try {
  const first = await storage.putResult({ jobId, leaseToken: tokenA, srt: "FIRST_RESULT" });
  assert.equal(first.key, keys[0]);
  console.log("FIRST WRITE: PASS");
  await assert.rejects(storage.putResult({ jobId, leaseToken: tokenA, srt: "OVERWRITTEN_RESULT" }), /R2_ATTEMPT_RESULT_ALREADY_EXISTS/);
  console.log("DUPLICATE WRITE REJECTED: PASS");
  const original = await storage.getResult({ key: keys[0] });
  assert.equal(original.toString(), "FIRST_RESULT");
  console.log("ORIGINAL CONTENT PRESERVED: PASS");

  const concurrent = await Promise.allSettled([
    storage.putResult({ jobId, leaseToken: tokenB, srt: "WORKER_A" }),
    storage.putResult({ jobId, leaseToken: tokenB, srt: "WORKER_B" }),
  ]);
  const successful = concurrent.filter(result => result.status === "fulfilled");
  const rejected = concurrent.filter(result => result.status === "rejected");
  assert.equal(successful.length, 1);
  assert.equal(rejected.length, 1);
  assert.match(String(rejected[0].reason?.message), /R2_ATTEMPT_RESULT_ALREADY_EXISTS/);
  const winnerIndex = concurrent.findIndex(result => result.status === "fulfilled");
  const winnerContent = winnerIndex === 0 ? "WORKER_A" : "WORKER_B";
  const concurrentResult = await storage.getResult({ key: keys[1] });
  assert.equal(concurrentResult.toString(), winnerContent);
  console.log("CONCURRENT CREATE-ONCE: PASS");
  console.log("WINNING RESULT PRESERVED: PASS");

  const newAttempt = await storage.putResult({ jobId, leaseToken: tokenC, srt: "NEW_LEASE_RESULT" });
  assert.notEqual(newAttempt.key, first.key);
  const newData = await storage.getResult({ key: newAttempt.key });
  assert.equal(newData.toString(), "NEW_LEASE_RESULT");
  console.log("NEW LEASE ISOLATION: PASS");
  passed = true;
} catch (error) {
  console.error("R2 CONDITIONAL TEST FAILED:", error.code || error.name || "UNKNOWN_ERROR");
  process.exitCode = 1;
} finally {
  // Only delete keys generated by this test.
  for (const key of keys) {
    try {
      await client.send(new DeleteObjectCommand({ Bucket: env.R2_BUCKET, Key: key }));
      try {
        await client.send(new HeadObjectCommand({ Bucket: env.R2_BUCKET, Key: key }));
        throw new Error("OBJECT_STILL_EXISTS");
      } catch (error) {
        if (error.name !== "NotFound" && error.$metadata?.httpStatusCode !== 404) throw error;
      }
    } catch (error) {
      cleanupPassed = false;
      console.error("R2 CLEANUP FAILED:", error.name);
      console.error("OBJECT KEY:", key);
    }
  }
  if (cleanupPassed) console.log("R2 TEST OBJECTS CLEANED: PASS");
  else process.exitCode = 1;
  client.destroy();
}
if (passed && cleanupPassed) console.log("TOOLNET-SRT R2 CONDITIONAL WRITE TEST PASSED");
