import type { SubtitleSegment } from "../asr/types.js";

function msToAssTime(ms: number): string {
  const h = Math.floor(ms / 3_600_000);
  const m = Math.floor((ms % 3_600_000) / 60_000);
  const s = Math.floor((ms % 60_000) / 1_000);
  const cs = Math.floor((ms % 1_000) / 10);
  return [
    String(h),
    String(m).padStart(2, "0"),
    String(s).padStart(2, "0"),
  ].join(":") +
    "." +
    String(cs).padStart(2, "0");
}

/**
 * Convert segments to ASS (Advanced SubStation Alpha) format.
 *
 * Includes a default style header with Arial/14pt white-on-black text.
 */
export function toAss(segments: SubtitleSegment[]): string {
  const header = [
    "[Script Info]",
    "Title: Generated by jianying-subtitle",
    "ScriptType: v4.00+",
    "WrapStyle: 0",
    "ScaledBorderAndShadow: yes",
    "YCbCr Matrix: None",
    "",
    "[V4+ Styles]",
    [
      "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour,",
      "OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut,",
      "ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow,",
      "Alignment, MarginL, MarginR, MarginV, Encoding",
    ].join(""),
    [
      "Style: Default,Arial,14,&H00FFFFFF,&H000000FF,",
      "&H00000000,&H80000000,-1,0,0,0,100,100,0,0,",
      "1,2,2,2,20,20,20,1",
    ].join(""),
    "",
    "[Events]",
    [
      "Format: Layer, Start, End, Style, Name, MarginL,",
      "MarginR, MarginV, Effect, Text",
    ].join(""),
  ].join("\n");

  const events = segments
    .map((seg) => {
      return [
        "Dialogue: 0,",
        msToAssTime(seg.startMs),
        ",",
        msToAssTime(seg.endMs),
        ",Default,,0,0,0,,",
        seg.text,
      ].join("");
    })
    .join("\n");

  return header + "\n" + events + "\n";
}
